#!/usr/bin/env python3
from __future__ import annotations

import argparse
from pathlib import Path
import tomllib


def format_include(inc):
    if inc.startswith("<") and inc.endswith(">"):
        return f"#include {inc}"
    return f'#include "{inc}"'


def split_includes(includes):
    local_incs = []
    sys_incs = []
    for inc in includes:
        if inc.startswith("<") and inc.endswith(">"):
            sys_incs.append(inc)
        else:
            local_incs.append(inc)
    return sorted(set(local_incs)), sorted(set(sys_incs))


def write_if_changed(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def generate_nodes_hpp(ns, families):
    lines = [
        "// Generated by tools/generate_ast.py. DO NOT EDIT.",
        "#pragma once",
        '#include "core/memory/arena.hpp"',
        "",
        "#include <utility>",
        "#include <variant>",
        "",
        f"namespace {ns} {{",
        "",
    ]

    for fam_name, fam in families.items():
        short = fam["short"]
        variant_name = fam["variant_name"]
        list_name = fam["list_name"]
        factory_name = fam["factory_name"]
        nodes = fam.get("nodes", {})

        for node_name in nodes:
            lines.append(f"struct {node_name}_{short};")
        lines.append("")

        lines.append(f"using {variant_name} = std::variant<")
        node_names = list(nodes.keys())
        for idx, node_name in enumerate(node_names):
            comma = "," if idx + 1 < len(node_names) else ""
            lines.append(f"    core::arena_ptr<{node_name}_{short}>{comma}")
        lines.append(">;")
        lines.append("")

        lines.append(f"using {list_name} = core::arena_vector<{variant_name}>;")
        lines.append("")

        lines.append("template <typename Node, typename... Args>")
        lines.append(f"[[nodiscard]] {variant_name} {factory_name}(core::arena& arena, Args&&... args) {{")
        lines.append("  return {core::make_object<Node>(arena, std::forward<Args>(args)...)};")
        lines.append("}")
        lines.append("")

    lines.append(f"}}  // namespace {ns}")
    lines.append("")
    return "\n".join(lines)


def generate_family_hpp(ns, fam_name, fam):
    short = fam["short"]
    nodes = fam.get("nodes", {})
    extra_includes = list(fam.get("includes", []))
    if fam_name == "statement":
        extra_includes.append("ast/expression.hpp")

    local_incs, sys_incs = split_includes(extra_includes)

    lines = [
        "// Generated by tools/generate_ast.py. DO NOT EDIT.",
        "#pragma once",
        '#include "ast/nodes.hpp"',
    ]
    for inc in local_incs:
        if inc != "ast/nodes.hpp":
            lines.append(format_include(inc))

    if sys_incs:
        lines.append("")
        for inc in sys_incs:
            lines.append(format_include(inc))

    lines.extend(["", f"namespace {ns} {{", ""])

    for node_name, node_data in nodes.items():
        struct_name = f"{node_name}_{short}"
        fields = node_data.get("fields", [])
        lines.append(f"struct {struct_name} {{")
        for field in fields:
            lines.append(f"  {field['type']} {field['name']};")
        lines.append("};")
        lines.append("")

    lines.append(f"}}  // namespace {ns}")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate C++ AST headers from TOML spec.")
    parser.add_argument("--input", required=True, type=Path, help="Path to nodes.toml")
    parser.add_argument("--out-dir", required=True, type=Path, help="Output directory for generated ast/ headers")
    args = parser.parse_args()

    data = tomllib.loads(args.input.read_text(encoding="utf-8"))
    ns = data.get("namespace", "cint::ast")
    families = data.get("families", {})

    ast_out = args.out_dir / "ast"

    write_if_changed(ast_out / "nodes.hpp", generate_nodes_hpp(ns, families))

    for fam_name, fam in families.items():
        file_stem = "expression.hpp" if fam_name == "expression" else (
            "statement.hpp" if fam_name == "statement" else f"{fam_name}.hpp"
        )
        write_if_changed(ast_out / file_stem, generate_family_hpp(ns, fam_name, fam))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
